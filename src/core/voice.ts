/**
 * The queue of spoken lines (docs/14-architecture.md, `src/core/voice`): pre-recorded Ukrainian clips with the device's
 * speech synthesis as the fallback, and the planner that decides which line may start. src/core/audio.ts re-exports
 * all of it, holds the sound and the music, and tells this module when the page is hidden and shown (TECH-05).
 */
import CLIPS from './clips.json';
import type { SpokenKey } from '../ui/strings';

const recorded = new Set<string>(CLIPS);   // regenerated by tools/gen_voice.py
let current: HTMLAudioElement | null = null;
/** The utterance of the line the synthesizer speaks now, so that hiding the page pauses it. */
let utter: SpeechSynthesisUtterance | null = null;
/** The page is hidden (TECH-05): the line is paused and nothing that waits for a line goes on until it is shown again. */
let hidden = false;
/** What waits for the page to be shown again: the ends of lines, lines asked for meanwhile, re-armed safety timers. */
const held: (() => void)[] = [];
/** The clip that hiding the page paused; it plays on from the same place when the page is shown. */
let pausedClip: HTMLAudioElement | null = null;
/** Settles the promise of the line that sounds now: a caller awaiting an interrupted line goes on at once, not when a safety timer fires. */
let endLine: (() => void) | null = null;
/** Priority of the line that sounds now (a silent reading pause counts as sounding); null in silence. */
let sounding: Priority | null = null;
let taskOpen = false;
const VOICE_WAIT_MS = 1500;
/** How many times a voice clip that failed to load is asked for again before the synthesizer says the line. */
export const CLIP_RETRIES = 1;
let ukVoice: SpeechSynthesisVoice | null = null;   // remembered once found
let listWait: Promise<void> | null = null;         // the one wait for the voice list, shared by the lines that start during it
let listWaited = false;
const base = import.meta.env.BASE_URL;
/** The voice volume: `volume.voice` of src/core/audio.ts, which src/main.ts and the parents' section change. */
let level = () => 1;
/** src/core/audio.ts hands in its voice volume. */
export function voiceVolume(get: () => number) { level = get; }

/** What the voice did in this session, for the walkthrough: clips that started to sound, and the ids of the lines left to the synthesizer. */
export const voiceLog = { clips: 0, synth: [] as string[] };
/** Ids of the lines the planner turned away, in order; for the walkthrough. Such a line is in neither list of `voiceLog`. */
export const dropped: string[] = [];

/** Runs `fn` now, or when the page is shown again if it is hidden. */
const whenShown = (fn: () => void) => { if (hidden) held.push(fn); else fn(); };
/** A safety timer of a line. Due while the page is hidden, it waits for the return and then counts its whole time again. */
function lineTimer(fn: () => void, ms: number) {
  const run = () => { if (hidden) held.push(() => setTimeout(run, ms)); else fn(); };
  setTimeout(run, ms);
}

/** The page is hidden (src/core/audio.ts `hide`): the clip pauses where it is and the synthesizer pauses. */
export function pauseVoice() {
  if (hidden) return;
  hidden = true;
  pausedClip = current && !current.paused && !current.ended ? current : null;
  pausedClip?.pause();
  if (utter && 'speechSynthesis' in window) speechSynthesis.pause();
}

/** The page is shown again (src/core/audio.ts `show`): the line goes on from where it stopped, then what waited. */
export function resumeVoice() {
  if (!hidden) return;
  hidden = false;
  if (pausedClip && pausedClip === current) pausedClip.play().catch(() => { /* its safety timer ends the line */ });
  pausedClip = null;
  if (utter && 'speechSynthesis' in window) speechSynthesis.resume();
  for (const fn of held.splice(0)) fn();
}

declare const spokenLine: unique symbol;
/**
 * The end of a spoken line. Only `say` makes one, so code that is required to speak (the task hooks) cannot satisfy
 * its type with a plain promise: showing a subtitle without the voice does not compile.
 */
export type Spoken = Promise<void> & { readonly [spokenLine]: true };

/** What a line is, highest first: a line of a task (its question, numbers, "try again", hint), the story, a background hint of the cat. */
export type Priority = 'task' | 'story' | 'hint';
const RANK: Record<Priority, number> = { hint: 0, story: 1, task: 2 };

/**
 * The planner's whole decision, free of Audio and DOM: may a new line start? `now` is the priority of the line that
 * sounds (null in silence). A lower line never cuts a higher one off; an equal or higher one does (a new mistake
 * cuts "try again" off). While a task is open only its own lines pass, even after its question has ended.
 */
export function mayStart(now: Priority | null, next: Priority, inTask: boolean): boolean {
  if (inTask && next !== 'task') return false;
  return now === null || RANK[next] >= RANK[now];
}
/** Would `say` start a line of this priority right now? Whoever shows a subtitle asks first: a line that is turned away shows nothing. */
export const willSay = (priority: Priority) => mayStart(sounding, priority, taskOpen);
/** True while a line sounds. */
export const speaking = () => sounding !== null;
/** The game opens a task: until `endTask` only lines of the `task` priority sound. */
export function beginTask() { taskOpen = true; }
/** The task is over, whichever way: its lines stop and no longer hold back the story that follows. */
export function endTask() { taskOpen = false; stopVoice(); }
export const inTask = () => taskOpen;

/**
 * Plays `voice/<id>.mp3`; if the clip is missing, falls back to the device's Ukrainian speech synthesis.
 * A line the planner turns away (see `mayStart`) starts nothing and its end is already settled.
 * `id` is a key of the list of spoken lines (VOICE-07): a key built on the spot (`tap_${n}`) does not compile.
 */
export function say(id: SpokenKey, text: string, priority: Priority): Spoken {
  if (!willSay(priority)) { dropped.push(id); return Promise.resolve() as Spoken; }
  return begin(priority, (finish, live) => { sound(id, text, finish, live); });
}

/**
 * A question of the bank of the old game's clips (VOICE-07, R37): `bank/<key>.mp3`, the keys and texts of
 * src/ui/strings-bank.ts. The bank is not part of the first load: a clip is fetched when first asked for and the
 * service worker keeps it (vite.config.ts, `runtimeCaching`).
 */
export type BankKey = `q_add_${number}_${number}` | `q_sub_${number}_${number}` | `q_count_${string}`
  | `q_before_${number}` | `q_after_${number}`;
/** How long the first download of a clip of the bank may take before the general question is said instead. */
const BANK_WAIT_MS = 4000;
const bankUrl = (key: BankKey) => new URL(`${base}bank/${key}.mp3`, location.href).href;

/**
 * Is the clip there to play? Online it is downloaded first with a plain request, answered in full, which the service
 * worker keeps (the player itself asks for byte ranges, and a partial answer is not kept). Without network only a clip
 * kept before counts, and nothing is asked for: no request leaves a device that has no network.
 */
async function bankReady(url: string, online: boolean): Promise<boolean> {
  try {
    if (!online) return 'caches' in window && (await caches.match(url)) !== undefined;
    const late = new Promise<null>((resolve) => { setTimeout(() => resolve(null), BANK_WAIT_MS); });
    const r = await Promise.race([fetch(url), late]);
    return r !== null && r.ok;
  } catch { return false; }
}

/**
 * Asks the very example with its clip of the bank (R37). A clip that is not there - not kept yet and no network, or
 * failed to load - gives way to the recorded general question `general` ("Скільки буде разом?"), never to the
 * synthesizer. `shown(bank)` tells which of the two is said, before it sounds, so that the subtitle follows the voice:
 * online the clip is expected (true at once, false if it fails), offline the answer of the cache decides.
 * The planner treats it as any line of `priority`.
 */
export function sayBank(key: BankKey, general: SpokenKey, text: string, priority: Priority, shown: (bank: boolean) => void): Spoken {
  if (!willSay(priority)) { dropped.push(key); return Promise.resolve() as Spoken; }
  const online = navigator.onLine !== false;
  if (online) shown(true);
  return begin(priority, (finish, live) => {
    const url = bankUrl(key);
    const instead = () => { if (!live()) return; shown(false); sound(general, text, finish, live); };
    lineTimer(finish, 15000);
    void bankReady(url, online).then((ok) => {
      if (!live()) return;
      if (!ok) { instead(); return; }
      if (!online) shown(true);
      playClip(url, 0, finish, live, instead);
    });
  });
}

/** Starts a line of `priority`: `body` makes it sound, on a shown page; the line ends with `finish`, `live` says it still may. */
function begin(priority: Priority, body: (finish: () => void, live: () => boolean) => void): Spoken {
  stopVoice();
  sounding = priority;
  return new Promise<void>((resolve) => {
    let done = false;
    // Safe to call again: Chrome reports a cancelled utterance through its own onend / onerror after stopVoice() has settled the line.
    // Only the line that still sounds leaves silence behind: a late call of an interrupted one must not hide its successor.
    // The awaiting code goes on only on a shown page: an end that comes while it is hidden is held until the return.
    const finish = () => { if (endLine === finish) { endLine = null; sounding = null; } done = true; whenShown(resolve); };
    const live = () => !done;
    endLine = finish;
    // A line asked for while the page is hidden starts when it is shown again (unless it is stopped before).
    whenShown(() => { if (!done) body(finish, live); });
  }) as Spoken;
}

/** A line of the list: its recorded clip, or the device's synthesizer when there is none or it fails to load. */
function sound(id: SpokenKey, text: string, finish: () => void, live: () => boolean) {
  if (!recorded.has(id)) { voiceLog.synth.push(id); speak(text, finish, live); return; }
  // A clip that failed to load is asked for once more before the device's synthesizer takes the line (TECH-08).
  playClip(`${base}voice/${id}.mp3`, CLIP_RETRIES, finish, live, () => { voiceLog.synth.push(id); speak(text, finish, live); });
  lineTimer(finish, 15000);
}

/** Plays the clip at `src`; one that fails to load is asked for `retries` more times, then `failed` takes the line. */
function playClip(src: string, retries: number, finish: () => void, live: () => boolean, failed: () => void) {
  const a = new Audio(src);
  a.volume = level();
  current = a;
  a.onplaying = () => { voiceLog.clips++; };
  a.onended = finish;
  a.onerror = () => { if (retries > 0) playClip(src, retries - 1, finish, live, failed); else failed(); };
  // A start refused because the page was hidden at that moment is not the end: the clip plays when it is shown.
  a.play().catch(() => { if (live() && (a.error || hidden)) return; finish(); });
}

/** Device speech synthesis; without a Ukrainian voice (or with the voice muted) the line is a silent pause long enough to read the subtitle. */
function speak(text: string, finish: () => void, live: () => boolean) {
  const pause = () => { lineTimer(finish, 900 + text.length * 55); };
  if (level() <= 0) { pause(); return; }
  withVoice((voice) => {
    if (!live()) return;                           // interrupted while the voice list was loading: must not start talking later
    if (!voice) { pause(); return; }
    const u = new SpeechSynthesisUtterance(text);
    u.voice = voice; u.lang = 'uk-UA'; u.rate = 0.9; u.pitch = 1.3; u.volume = level();
    u.onend = finish; u.onerror = finish;
    utter = u;
    speechSynthesis.speak(u);
    lineTimer(finish, 12000);
  });
}

/**
 * Hands the device's Ukrainian voice, or null, to `use`. Browsers (Android Chrome among them) load the voice list
 * asynchronously: the first getVoices() is empty and the list comes with `voiceschanged`. So the first line of a session
 * waits for the list - once, and no longer than VOICE_WAIT_MS - instead of passing in silence.
 */
function withVoice(use: (voice: SpeechSynthesisVoice | null) => void) {
  if (ukVoice || !('speechSynthesis' in window)) { use(ukVoice); return; }
  const synth = speechSynthesis;
  const look = () => {
    const voices = synth.getVoices();
    ukVoice = voices.find((v) => v.lang.toLowerCase().startsWith('uk')) ?? null;
    return voices.length > 0;
  };
  if (look() || listWaited) { use(ukVoice); return; }
  listWait ??= new Promise<void>((resolve) => {
    const settle = () => {
      clearTimeout(timer); synth.removeEventListener?.('voiceschanged', onChange);
      listWaited = true; listWait = null; resolve();
    };
    const onChange = () => { if (look()) settle(); };
    const timer = setTimeout(() => { look(); settle(); }, VOICE_WAIT_MS);   // the last look: not every browser fires the event
    synth.addEventListener?.('voiceschanged', onChange);                    // `?.`: in older Safari speechSynthesis is not an EventTarget
  });
  void listWait.then(() => use(ukVoice));
}

export function stopVoice() {
  const end = endLine; endLine = null; sounding = null; utter = null;
  if (current) { current.onplaying = null; current.onended = null; current.onerror = null; current.pause(); current = null; }
  if ('speechSynthesis' in window) speechSynthesis.cancel();
  end?.();
}
