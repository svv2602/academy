/** Voice clips (pre-recorded Ukrainian), synthesized SFX and a soft generative music bed. */
import CLIPS from './clips.json';

const recorded = new Set<string>(CLIPS);   // regenerated by tools/gen_voice.py
let ctx: AudioContext | null = null;
let musicGain: GainNode, sfxGain: GainNode;
let current: HTMLAudioElement | null = null;
/** Settles the promise of the line that sounds now: a caller awaiting an interrupted line goes on at once, not when a safety timer fires. */
let endLine: (() => void) | null = null;
/** Priority of the line that sounds now (a silent reading pause counts as sounding); null in silence. */
let sounding: Priority | null = null;
let taskOpen = false;
const VOICE_WAIT_MS = 1500;
let ukVoice: SpeechSynthesisVoice | null = null;   // remembered once found
let listWait: Promise<void> | null = null;         // the one wait for the voice list, shared by the lines that start during it
let listWaited = false;
const base = import.meta.env.BASE_URL;

export const volume = { music: 0.5, sfx: 0.8, voice: 1 };
/** What the voice did in this session, for the walkthrough: clips that started to sound, and the ids of the lines left to the synthesizer. */
export const voiceLog = { clips: 0, synth: [] as string[] };
/** Ids of the lines the planner turned away, in order; for the walkthrough. Such a line is in neither list of `voiceLog`. */
export const dropped: string[] = [];

export function unlockAudio() {
  if (ctx) { void ctx.resume(); return; }
  const AC = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
  if (!AC) return;
  ctx = new AC();
  musicGain = ctx.createGain(); musicGain.gain.value = volume.music * 0.22; musicGain.connect(ctx.destination);
  sfxGain = ctx.createGain(); sfxGain.gain.value = volume.sfx * 0.5; sfxGain.connect(ctx.destination);
  startMusic();
}

declare const spokenLine: unique symbol;
/**
 * The end of a spoken line. Only `say` makes one, so code that is required to speak (the task hooks) cannot satisfy
 * its type with a plain promise: showing a subtitle without the voice does not compile.
 */
export type Spoken = Promise<void> & { readonly [spokenLine]: true };

/** What a line is, highest first: a line of a task (its question, numbers, "try again", hint), the story, a background hint of the cat. */
export type Priority = 'task' | 'story' | 'hint';
const RANK: Record<Priority, number> = { hint: 0, story: 1, task: 2 };

/**
 * The planner's whole decision, free of Audio and DOM: may a new line start? `now` is the priority of the line that
 * sounds (null in silence). A lower line never cuts a higher one off; an equal or higher one does (a new mistake
 * cuts "try again" off). While a task is open only its own lines pass, even after its question has ended.
 */
export function mayStart(now: Priority | null, next: Priority, inTask: boolean): boolean {
  if (inTask && next !== 'task') return false;
  return now === null || RANK[next] >= RANK[now];
}
/** Would `say` start a line of this priority right now? Whoever shows a subtitle asks first: a line that is turned away shows nothing. */
export const willSay = (priority: Priority) => mayStart(sounding, priority, taskOpen);
/** True while a line sounds. */
export const speaking = () => sounding !== null;
/** The game opens a task: until `endTask` only lines of the `task` priority sound. */
export function beginTask() { taskOpen = true; }
/** The task is over, whichever way: its lines stop and no longer hold back the story that follows. */
export function endTask() { taskOpen = false; stopVoice(); }
export const inTask = () => taskOpen;

/**
 * Plays `voice/<id>.mp3`; if the clip is missing, falls back to the device's Ukrainian speech synthesis.
 * A line the planner turns away (see `mayStart`) starts nothing and its end is already settled.
 */
export function say(id: string, text: string, priority: Priority): Spoken {
  if (!willSay(priority)) { dropped.push(id); return Promise.resolve() as Spoken; }
  stopVoice();
  sounding = priority;
  return new Promise<void>((resolve) => {
    let done = false;
    // Safe to call again: Chrome reports a cancelled utterance through its own onend / onerror after stopVoice() has settled the line.
    // Only the line that still sounds leaves silence behind: a late call of an interrupted one must not hide its successor.
    const finish = () => { if (endLine === finish) { endLine = null; sounding = null; } done = true; resolve(); };
    const live = () => !done;
    endLine = finish;
    if (!recorded.has(id)) { voiceLog.synth.push(id); speak(text, finish, live); return; }
    const a = new Audio(`${base}voice/${id}.mp3`);
    a.volume = volume.voice;
    current = a;
    a.onplaying = () => { voiceLog.clips++; };
    a.onended = finish;
    a.onerror = () => { voiceLog.synth.push(id); speak(text, finish, live); };
    a.play().catch(() => { if (!done && a.error) return; finish(); });
    setTimeout(finish, 15000);
  }) as Spoken;
}

/** Device speech synthesis; without a Ukrainian voice (or with the voice muted) the line is a silent pause long enough to read the subtitle. */
function speak(text: string, finish: () => void, live: () => boolean) {
  const pause = () => { setTimeout(finish, 900 + text.length * 55); };
  if (volume.voice <= 0) { pause(); return; }
  withVoice((voice) => {
    if (!live()) return;                           // interrupted while the voice list was loading: must not start talking later
    if (!voice) { pause(); return; }
    const u = new SpeechSynthesisUtterance(text);
    u.voice = voice; u.lang = 'uk-UA'; u.rate = 0.9; u.pitch = 1.3; u.volume = volume.voice;
    u.onend = finish; u.onerror = finish;
    speechSynthesis.speak(u);
    setTimeout(finish, 12000);
  });
}

/**
 * Hands the device's Ukrainian voice, or null, to `use`. Browsers (Android Chrome among them) load the voice list
 * asynchronously: the first getVoices() is empty and the list comes with `voiceschanged`. So the first line of a session
 * waits for the list - once, and no longer than VOICE_WAIT_MS - instead of passing in silence.
 */
function withVoice(use: (voice: SpeechSynthesisVoice | null) => void) {
  if (ukVoice || !('speechSynthesis' in window)) { use(ukVoice); return; }
  const synth = speechSynthesis;
  const look = () => {
    const voices = synth.getVoices();
    ukVoice = voices.find((v) => v.lang.toLowerCase().startsWith('uk')) ?? null;
    return voices.length > 0;
  };
  if (look() || listWaited) { use(ukVoice); return; }
  listWait ??= new Promise<void>((resolve) => {
    const settle = () => {
      clearTimeout(timer); synth.removeEventListener?.('voiceschanged', onChange);
      listWaited = true; listWait = null; resolve();
    };
    const onChange = () => { if (look()) settle(); };
    const timer = setTimeout(() => { look(); settle(); }, VOICE_WAIT_MS);   // the last look: not every browser fires the event
    synth.addEventListener?.('voiceschanged', onChange);                    // `?.`: in older Safari speechSynthesis is not an EventTarget
  });
  void listWait.then(() => use(ukVoice));
}

export function stopVoice() {
  const end = endLine; endLine = null; sounding = null;
  if (current) { current.onplaying = null; current.onended = null; current.onerror = null; current.pause(); current = null; }
  if ('speechSynthesis' in window) speechSynthesis.cancel();
  end?.();
}

function tone(freq: number, t0: number, dur: number, type: OscillatorType, peak: number, out: AudioNode) {
  if (!ctx) return;
  const o = ctx.createOscillator(), g = ctx.createGain();
  o.type = type; o.frequency.value = freq;
  g.gain.setValueAtTime(0, t0);
  g.gain.linearRampToValueAtTime(peak, t0 + 0.015);
  g.gain.exponentialRampToValueAtTime(0.0005, t0 + dur);
  o.connect(g); g.connect(out);
  o.start(t0); o.stop(t0 + dur + 0.05);
}

export function sfx(kind: 'pop' | 'chime' | 'good' | 'soft' | 'fanfare' | 'jump') {
  if (!ctx) return;
  const t = ctx.currentTime;
  const seq: Record<string, [number, number, number][]> = {
    pop: [[660, 0, 0.12]],
    jump: [[392, 0, 0.1], [523, 0.05, 0.14]],
    chime: [[1047, 0, 0.5], [1319, 0.08, 0.5], [1568, 0.16, 0.7]],
    good: [[784, 0, 0.25], [988, 0.1, 0.25], [1175, 0.2, 0.5]],
    soft: [[440, 0, 0.3], [392, 0.14, 0.4]],
    fanfare: [[523, 0, 0.4], [659, 0.15, 0.4], [784, 0.3, 0.4], [1047, 0.45, 0.9], [1319, 0.75, 1.2], [1568, 0.9, 1.6]],
  };
  for (const [f, at, dur] of seq[kind]) {
    tone(f, t + at, dur, 'sine', 0.5, sfxGain);
    tone(f * 2, t + at, dur * 0.6, 'triangle', 0.12, sfxGain);
  }
}

/** Slow pentatonic bells over a quiet pad: endless, never repeats exactly, costs nothing to ship. */
function startMusic() {
  if (!ctx) return;
  const c = ctx;
  const delay = c.createDelay(1); delay.delayTime.value = 0.42;
  const fb = c.createGain(); fb.gain.value = 0.35;
  delay.connect(fb); fb.connect(delay); delay.connect(musicGain);
  const scale = [261.6, 293.7, 329.6, 392, 440, 523.3, 587.3, 659.3, 784];
  const chords = [[130.8, 196, 329.6], [110, 164.8, 261.6], [87.3, 174.6, 261.6], [98, 196, 293.7]];
  let next = c.currentTime + 0.3, bar = 0, idx = 4;
  const schedule = () => {
    while (next < c.currentTime + 1.5) {
      if (bar % 8 === 0) {
        for (const f of chords[(bar / 8) % chords.length]) {
          const o = c.createOscillator(), g = c.createGain();
          o.type = 'sine'; o.frequency.value = f;
          g.gain.setValueAtTime(0, next);
          g.gain.linearRampToValueAtTime(0.16, next + 1.5);
          g.gain.linearRampToValueAtTime(0, next + 4.6);
          o.connect(g); g.connect(musicGain); o.start(next); o.stop(next + 4.7);
        }
      }
      if (Math.random() < 0.62) {
        idx = Math.max(0, Math.min(scale.length - 1, idx + Math.floor(Math.random() * 5) - 2));
        tone(scale[idx], next, 1.4, 'sine', 0.3, musicGain);
        tone(scale[idx], next, 1.4, 'sine', 0.18, delay);
      }
      next += 0.55; bar++;
    }
  };
  schedule();
  setInterval(schedule, 400);
}

export function setVolumes() {
  if (!ctx) return;
  musicGain.gain.value = volume.music * 0.22;
  sfxGain.gain.value = volume.sfx * 0.5;
}
